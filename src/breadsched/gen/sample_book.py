"""Create an explicitly synthetic household book for learning the workflows."""

from __future__ import annotations

from datetime import date, timedelta
from pathlib import Path

from .db.sqlite import DbSQLite
from .engine.dashboard import DashboardConfig, GroupConfig
from .lib import (
    Account,
    AccountType,
    Assumptions,
    Money,
    PeriodType,
    Recurrence,
    Scenario,
    ScheduledSplit,
    ScheduledTransaction,
    Transaction,
)


def create_sample_book(path: Path, *, as_of: date) -> None:
    """Write a standalone sample without reading or altering another book.

    The same reference date yields the same chart, dates, amounts, and plan.
    Object handles are generated by the normal book API and need not match.
    """
    if path.exists():
        raise FileExistsError(path)
    if not path.parent.is_dir():
        raise FileNotFoundError(path.parent)

    month_start = as_of.replace(day=1)
    previous = (month_start - timedelta(days=1)).replace(day=1)
    next_month = (month_start.replace(day=28) + timedelta(days=4)).replace(day=1)
    db = DbSQLite()
    created = False
    try:
        db.load(str(path))
        created = True
        with db.transaction("Create synthetic sample household") as txn:
            root = Account(name="Root", atype=AccountType.ROOT)
            db.add_account(root, txn)

            def account(
                name: str, kind: AccountType, parent: Account, *, placeholder: bool = False
            ) -> Account:
                item = Account(name=name, atype=kind, parent=parent.handle, placeholder=placeholder)
                db.add_account(item, txn)
                return item

            assets = account("Assets", AccountType.ASSET, root, placeholder=True)
            liabilities = account("Liabilities", AccountType.LIABILITY, root, placeholder=True)
            income = account("Income", AccountType.INCOME, root, placeholder=True)
            expenses = account("Expenses", AccountType.EXPENSE, root, placeholder=True)
            equity = account("Equity", AccountType.EQUITY, root, placeholder=True)
            checking = account("Checking", AccountType.BANK, assets)
            savings = account("Savings", AccountType.BANK, assets)
            card = account("Credit card", AccountType.CREDIT, liabilities)
            salary = account("Wages", AccountType.INCOME, income)
            housing = account("Housing", AccountType.EXPENSE, expenses)
            food = account("Groceries", AccountType.EXPENSE, expenses)
            utilities = account("Utilities", AccountType.EXPENSE, expenses)
            opening = account("Opening balances", AccountType.EQUITY, equity)

            for when, label, debit, credit, amount in (
                (previous, "Sample opening checking", checking, opening, "3500"),
                (previous, "Sample opening savings", savings, opening, "8000"),
                (previous, "Sample opening card balance", opening, card, "350"),
                (previous.replace(day=5), "Sample wages", checking, salary, "4200"),
                (previous.replace(day=6), "Sample rent", housing, checking, "1450"),
                (previous.replace(day=12), "Sample groceries", food, checking, "320"),
                (previous.replace(day=20), "Sample utilities", utilities, checking, "180"),
            ):
                db.add_transaction(
                    Transaction.simple(when, label, debit.handle, credit.handle, amount), txn
                )

            for label, debit, credit, amount, day, estimate in (
                ("Sample wages", checking, salary, "4200", 5, False),
                ("Sample rent", housing, checking, "1450", 6, False),
                ("Sample groceries plan", food, checking, "350", 12, True),
                ("Sample utilities", utilities, checking, "180", 20, False),
            ):
                scheduled = ScheduledTransaction(
                    name=label,
                    recurrence=Recurrence(PeriodType.MONTH, start=next_month.replace(day=day)),
                    splits=[
                        ScheduledSplit(debit.handle, Money(amount)),
                        ScheduledSplit(credit.handle, -Money(amount)),
                    ],
                )
                scheduled.placeholder = estimate
                db.add_scheduled(scheduled, txn)

            db.add_scenario(
                Scenario(name="Base", start=next_month, years=2, assumptions=Assumptions()),
                txn,
            )
        DashboardConfig(
            groups=[
                GroupConfig("Cash", [checking.handle, savings.handle], "liquid"),
                GroupConfig("Card debt", [card.handle], "liability"),
            ]
        ).save(db)
        db.set_metadata("book_name", "SYNTHETIC SAMPLE — no real financial data")
    except Exception:
        db.close()
        if created:
            path.unlink(missing_ok=True)
        raise
    else:
        db.close()
